-- EDD-OSS-DSN-CR-003 §6.1：通用业务日志对象表
CREATE TABLE IF NOT EXISTS `tb_log_object`
(
    `id`              BIGINT       NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    `object_id`       VARCHAR(36)  NOT NULL COMMENT '外部对象标识 UUID',
    `provider`        VARCHAR(32)  NOT NULL COMMENT '存储提供方，固定 TENCENT_COS',
    `region`          VARCHAR(32)  NOT NULL COMMENT '授权时 COS 地域快照',
    `bucket_name`     VARCHAR(128) NOT NULL COMMENT '授权时私有日志 Bucket 快照',
    `caller_service`  VARCHAR(64)  NOT NULL COMMENT '调用方归属命名空间',
    `business_type`   VARCHAR(64)  NOT NULL COMMENT '业务类型，本期 OTA_UPGRADE_LOG',
    `business_id`     VARCHAR(128) NOT NULL COMMENT '业务主标识，本期 vehicleTaskId',
    `business_sub_id` VARCHAR(128) NULL COMMENT '业务子标识，本期可选 executionId',
    `request_id`      VARCHAR(128) NOT NULL COMMENT '调用方幂等键',
    `file_name`       VARCHAR(255) NOT NULL COMMENT '原始文件名，仅元数据',
    `object_key`      VARCHAR(512) NOT NULL COMMENT 'OSS 生成对象键',
    `content_type`    VARCHAR(64)  NOT NULL COMMENT '声明 Content-Type',
    `declared_size`   BIGINT       NOT NULL COMMENT '声明字节数',
    `actual_size`     BIGINT       NULL COMMENT 'HEAD 实际字节数',
    `declared_sha256` CHAR(64)     NOT NULL COMMENT '声明 SHA-256，小写十六进制',
    `actual_sha256`   CHAR(64)     NULL COMMENT 'HEAD x-cos-meta-sha256',
    `etag`            VARCHAR(255) NULL COMMENT 'HEAD ETag，仅登记',
    `privacy_level`   VARCHAR(32)  NOT NULL COMMENT '隐私分级元数据',
    `upload_state`    VARCHAR(16)  NOT NULL COMMENT '状态：AUTHORIZED/UPLOADED/FAILED/EXPIRED',
    `failure_reason`  VARCHAR(64)  NULL COMMENT '稳定失败原因码',
    `authorized_at`   TIMESTAMP(3) NOT NULL COMMENT '授权登记时间',
    `uploaded_at`     TIMESTAMP(3) NULL COMMENT '核验成功时间',
    `expires_at`      TIMESTAMP(3) NOT NULL COMMENT '上传授权过期时间',
    `received_at`     TIMESTAMP(3) NULL COMMENT '首次 complete 受理时间',
    `description`     VARCHAR(255) NULL COMMENT '描述；不保存日志正文或 URL',
    `create_by`       VARCHAR(64)  NULL COMMENT '创建方',
    `create_time`     TIMESTAMP(3) NOT NULL COMMENT '审计创建时间',
    `modify_by`       VARCHAR(64)  NULL COMMENT '最后修改方',
    `modify_time`     TIMESTAMP(3) NULL COMMENT '审计修改时间',
    `row_version`     INT          NOT NULL DEFAULT 1 COMMENT '乐观锁',
    `row_valid`       TINYINT      NOT NULL DEFAULT 1 COMMENT '逻辑有效标记；业务终态不置 0',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_log_object_id` (`object_id`),
    UNIQUE KEY `uk_log_request` (`caller_service`, `business_type`, `request_id`),
    UNIQUE KEY `uk_log_object_key` (`object_key`),
    KEY `idx_log_business_id` (`business_type`, `business_id`, `id`),
    KEY `idx_log_business_sub_id` (`business_sub_id`),
    KEY `idx_log_caller_state_id` (`caller_service`, `upload_state`, `id`),
    KEY `idx_log_authorized_at` (`authorized_at`),
    KEY `idx_log_expiration` (`upload_state`, `expires_at`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4 COMMENT ='通用业务日志对象表';
